    public void agregarFila(int bcpId, int memDir, String estado) {
        DefaultTableModel model = (DefaultTableModel) bcps.getModel();
        model.addRow(new Object[]{bcpId, memDir, estado});
    }
    
    public void eliminarFilaPorId(int bcpId) {
        DefaultTableModel model = (DefaultTableModel) bcps.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            if ((int) model.getValueAt(i, 0) == bcpId) { // Verifica si el valor de BCP ID coincide
                model.removeRow(i); // Elimina la fila
                break; // Detiene el bucle después de eliminar
            }
        }
    }

